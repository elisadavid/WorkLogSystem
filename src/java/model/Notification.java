package model;

import java.security.Timestamp;

/**
 *
 * @author Trainee2
 */
public class Notification {

    private int notifId;
    private String recipientId;     // The ID of the user receiving the notification (Head or Staff)
    private String userRole;     // "HEAD" or "STAFF" to know who the notification is for
    private String title;        // e.g., "New Trainee Assigned"
    private String message;      // e.g., "Mentor John has accepted trainee T-101"
    private String status;       // "UNREAD" or "READ"
    private String createdAt; // Date and time of notification

    public int getNotifId() {
        return notifId;
    }

    public void setNotifId(int notifId) {
        this.notifId = notifId;
    }

    public String getRecipientId() {
        return recipientId;
    }

    public void setRecipientId(String recipientId) {
        this.recipientId = recipientId;
    }

    public String getUserRole() {
        return userRole;
    }

    public void setUserRole(String userRole) {
        this.userRole = userRole;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(String createdAt) {
        this.createdAt = createdAt;
    }

}
