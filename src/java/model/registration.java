public class registration {

    private int mentorId;
    private String staffCode;
    private String fullName;
    private String email;
    private String password;
    private String phone;
    private String department;
    private String mentorDesignationId; // Use int if you switched to designation_id

    public int getMentorId() {
        return mentorId;
    }

    public void setMentorId(int mentorId) {
        this.mentorId = mentorId;
    }

    public String getStaffCode() {
        return staffCode;
    }

    public void setStaffCode(String staffCode) {
        this.staffCode = staffCode;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }

    public String getMentorDesignationId() {
        return mentorDesignationId;
    }

    public void setMentorDesignationId(String mentorDesignationId) {
        this.mentorDesignationId = mentorDesignationId;
    }
}
